                                'statusList' => [],
                                'roleList'   => [],
                            ],
                            'on afterCreateQuery' => function ($event) use ($modelClass, $relations, $attributes, $attributesTranslate) {
                                //dd($event);
                                //dd('Есть $relations=', $relations);exit();

                                // Если есть переводы
                                if (isset($relations['translations'])) {
                                    $trAlias = 'translate';
                                    $event->query->select[$modelClass::tableName() . '_id'] =
                                        $trAlias . '.' . $modelClass::tableName() . '_id';
                                    $event->query->select['language_id'] = $trAlias . '.language_id';

