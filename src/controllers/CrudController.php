                                    foreach ($attributesTranslate as $fieldName) {
                                        $event->query->select[$fieldName] = $trAlias . '.' . $fieldName;
                                    }

                                    // Приджойним таблицу с переводами
                                    $event->query->leftJoin(
                                        $modelClass::tableName() . '_translation AS ' . $trAlias,
                                        $trAlias . '.' . $relations['translations']['attribute'] . ' = self.id'
                                    );
                                    $event->query->groupBy('self.id');

                                    unset($relations['translations']);
                                    unset($relations['defaultTranslation']);
                                }
                                //dd('Есть $relations=', $relations);
                                //$zzz = $event->query;
                                //dd($zzz->prepare(\Yii::$app->db->queryBuilder)->createCommand()->rawSql);

                                if ($relations) {
                                    //dd('Есть необработанные $relations=', $relations);exit();

                                    $searchTypes = $event->sender->getSearchAttributeTypes();

                                    foreach ($relations as $relation => $relParams) {
                                        if ($relParams instanceof Closure) {
                                            continue;
                                        }
                                        //dd($relation, $relParams);

                                        //$key = $relParams['table'] . '_id';
                                        //$key = ($relParams['table'] ?? $relation) . '_id';
                                        //dd([$key, $searchTypes, $event->sender]);
                                        $key = $relParams['attribute'];

                                        // Если есть тип для поля и есть значение для поиска
                                        if (isset($searchTypes[$key]) && !empty($event->sender->{$key})) {
                                            // Если нет via-таблицы
                                            if (empty($relParams['via'])) {
                                                //$event->query->joinWith($relation);
                                                //dd($relParams);
                                                // Приджойним таблицу с переводами
                                                $event->query->leftJoin(
                                                    $relParams['table'] . ' AS ' . ($relParams['slug'] ?? $relParams['table']),
                                                    $relParams['table'] . '.id = self.' . $relParams['attribute']
                                                );
                                                //dd($event->query->prepare(Yii::$app->db->queryBuilder)->createCommand()->rawSql);
                                            } else {
                                                dd('Есть via-таблица=', $relParams['via']);
                                                //// Есть via-таблица
                                                //foreach ($relations as $relation1 => $relParams1) {
                                                //    if ($relParams1 instanceof Closure) {
                                                //        continue;
                                                //    }
                                                //    if ($relParams1['table'] === $relParams['via']) {
                                                //        // ? По идее должно быть связь, чтобы вызывать joinWith
                                                //        //$query = $this->hasMany($className, ['id' => $relation['table'] . '_id'])
                                                //        //    ->viaTable($relation['via'], [$relation['attribute'] => 'id']);
                                                //        //$event->query->joinWith($relation1);
                                                //        $event->query->leftJoin(
                                                //            $relation1,
                                                //            $relParams1['attribute'].' = self.id'
                                                //        );
                                                //    }
                                                //}
                                            }
                                        }
                                    }
                                }
                            },
                        ]);
                    },
                ],
                'edit' => [
                    'class' => EditableColumnAction::class,
                    'modelClass' => $this->modelClass,
                    'outputValue' => function (ActiveRecord $model, $attribute, $key, $index) {
                        $type = ArrayHelper::getValue(
                            Yii::$app->params,
                            'tables.' . $model->tableName() . '.columns.' . $attribute . '.type',
                            ''
                        );
                        if ($type == 'boolean' || $model->getTableSchema()->getColumn($attribute)->type == 'boolean') {
                            return Html::icon(
                                $model->$attribute ? 'check text-success' : 'times text-danger',
                                [],
                                'fa fa-'
                            );
                        }

                        return $model->$attribute;
                    },
                ],
                'toggle' => [
                    'class' => ToggleAction::class,
                    'modelClass' => $this->modelClass,
                    //// if you want to use flash messages
                    //'setFlash'     => true,
                    //'flashSuccess' => 'Success message',
                    //'flashError'   => 'Error message',
                    ///*'redirect'     => 'some-redirect-url',
                    // if you want to use custom code before saving the model
                    'preProcess' => function ($vars) {
                        if ($_REQUEST['attribute'] == 'default') {
                            $modelClass = $this->modelClass;
                            $modelClass::updateAll(['default' => 0,]);
                        }
                    },
                ],
            ]
        );

        $table = Yii::$app->request->get('table');
        $info = ArrayHelper::getValue(Yii::$app->params, 'tables.' . $table, []);
        foreach ($info as $key => $value) {
            // Если у таблицы есть actions
            if ($key === 'actions') {
                foreach ($value as $uKey => $action) {
                    $actions[$uKey] = [
                        'class'    => CallbackAction::class,
                        'callback' => $action,
                    ];
                }
            }
            // Если у таблицы есть список полей formFields
