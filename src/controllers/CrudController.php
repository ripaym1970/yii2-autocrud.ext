class CrudController extends \yii2tech\admin\CrudController
{
    public $modelClass = 'ripaym1970\autocrud\models\crud\{Table}Model';

    public $createScenario = 'create';

    public $table = ''; // Только для common/components/actions/CreateAction.php

    private $_table;

    private $_roles = ['editor', 'moderator', 'admin'];

    /**
     * @throws NotFoundHttpException
     */
    public function init()
    {
        parent::init();
        $this->_table = Yii::$app->request->get('table');
        $this->_table = $this->_table ?? Yii::$app->request->post('table');

        $issetTable = isset(Yii::$app->params['tables'][$this->_table]);
        if (!$issetTable) {
            throw new NotFoundHttpException('Table "' . $this->_table . '" not found');
        }

        $isCrud = Yii::$app->params['tables'][$this->_table]['crud_edit'] ?? true;
        //dd('$isCrud=',$isCrud);
        if (!$isCrud) {
            throw new NotFoundHttpException('Table "' . $this->_table . '" cannot be edited');
        }

        //$this->modelClass = 'ripaym1970\autocrud\models\crud\\' . Inflector::id2camel($table, '_') . 'Model';
        $this->modelClass = 'ripaym1970\autocrud\models\crud\\' . ucfirst($this->_table) . 'Model';
        $this->table = $this->_table;
        if (!empty(Yii::$app->params['tables'][$this->_table]['roles'])) {
            $this->_roles = Yii::$app->params['tables'][$this->_table]['roles'];
        }
    }

    public function beforeAction($action)
    {
        /** @var $identity AdminModel */
        $identity = Yii::$app->user->identity;
        //dd($identity->role, $this->_roles);
        if (!$identity || !in_array($identity->role, $this->_roles)) {
            throw new HttpException(404, 'У вас нет прав на просмотр этой страницы');
        }

        return parent::beforeAction($action); // TODO: Change the autogenerated stub
    }

    public function actions()
    {
        $parentActions = parent::actions();
        unset($parentActions['view']);
        $actions = ArrayHelper::merge(
            $parentActions,
            [
                'cache-flush'  => [
                    'class' => CacheFlushAction::class,
                ],
                'np-download'         => [
                    'class' => NpDownloadAction::class,
                ],
                'list'         => [
                    'class' => ListAction::class,
                ],
                'delete-image' => [
                    'class' => DeleteImageAction::class,
                ],
                'move-image-up'      => [
                    'class' => MoveImageUpAction::class,
                ],
                'move-image-down'    => [
                    'class' => MoveImageDownAction::class,
                ],
                'move-up'      => [
                    'class' => MoveUpAction::class,
                ],
                'move-down'    => [
                    'class' => MoveDownAction::class,
                ],
                'position'     => [
                    'class' => PositionAction::class,
                ],
                'delete'       => [
                    'class' => DeleteAction::class,
                ],
                'view'         => [
                    'class'        => ViewAction::class,
                ],
                'create'       => [
                    'class'    => CreateAction::class,
                    'scenario' => $this->createScenario,
                ],
                'update'       => [
                    'class'    => UpdateAction::class,
                    'scenario' => $this->updateScenario,
                ],
                'index'        => [
                    'newSearchModel' => function () {
                        $modelClass = $this->modelClass;
                        $tableName = $modelClass::tableName();
                        $query = $this->getQueryList($modelClass);

                        // Получим для сортировки поля модели
                        $columns = ArrayHelper::getValue(Yii::$app->params, 'tables.' . $tableName . '.columns', []);
                        $attributes = array_keys($columns);

                        // Получим связи
                        $tableRelations = ArrayHelper::getValue(Yii::$app->params, 'tables.' . $tableName . '.relations', []);
                        //dd('Получим связи $tableRelations=', $tableRelations);
                        $relations = prepareRelations($tableRelations);

                        $attributesTranslate = [];
                        // Если есть переводы
                        if (isset($relations['translations'])) {
                            // Получим для сортировки поля переводов
                            $attributesTranslate = array_keys(
                                ArrayHelper::getValue(
                                    Yii::$app->params,
                                    'tables.' . $modelClass::tableName() . '.behaviors.translations.variationAttributeDefaultValueMap',
                                    []
                                )
                            );
                            $attributes = array_merge($attributes, $attributesTranslate);
                        }
                        //dd($attributes);

                        return new ActiveSearchModel([
                            'model'               => $this->modelClass,
                            'dataProvider'        => [
                                'class'      => 'yii\data\ActiveDataProvider',
                                'pagination' => [
                                    'defaultPageSize' => 10,
                                    'pageSizeLimit'   => [10, 20, 50, 75, 100, 150, 200],
                                ],
                                'sort'       => [
                                    'attributes'   => $attributes,
                                    'defaultOrder' => ArrayHelper::getValue(
                                        Yii::$app->params,
                                        'tables.' . $modelClass::tableName() . '.defaultOrder',
