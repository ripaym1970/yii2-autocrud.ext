                $uKey = strtolower(substr($key, 10) ?: 'update');
                //dd('$uKey=',$uKey);
                $actions[$uKey] = [
                    'class'    => UpdateAction::class,
                    'scenario' => $this->updateScenario,
                    'form'     => $uKey !== 'update' ? $uKey : '',
                ];
                //dd('$actions=',$uKey,$actions[$uKey]);
            }
        }

        return $actions;
    }

    /**
     * @param $modelClass
     *
     * @return ActiveQuery
     */
    public static function getQueryList($modelClass)
    {
        return $modelClass::find()
            ->alias('self')
            ->select([
                'self.*',
            ]);
    }
}
